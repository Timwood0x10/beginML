// Per-experiment UI copy — Question / Challenge / Explanation / Notes and
// free-standing strings, so lab components never hard-code a language.
// Templates may contain {var} placeholders filled by fmt() below.

export interface LabTexts {
  question: string
  challengeQuestion: string
  challengeOptions: { value: string; label: string }[]
  explanation: string[]
  notes: { title: string; src: string }[]
  aha?: string
  ui: Record<string, string>
}

/** Fill {var} placeholders in a translated template (unknown keys become ''). */
export function fmt(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''))
}

